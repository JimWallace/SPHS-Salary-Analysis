#!/usr/bin/env python3
"""Macros comparing the anomaly screen with the March (SPHS growth) and October (promotion) reports.

Usage:
  python3 scripts/anomaly_cross_report.py

Reads only committed aggregate outputs of the earlier reports, plus the subject's own row:
- analysis_output/lme4_growth_model_summary.csv      (March: multilevel growth gap and level gap)
- analysis_output/entry_cohort_growth_summary.csv    (March: career-stage-aligned slope gaps)
- analysis_output/promotion_pool_2025.tex            (October: gaps to the pool quartiles; \\input by the report)
- analysis_output/anomaly_subject_results.csv        (this report)
- data/private/anomaly_inputs.csv                    (subject's years since hire only)

Output: analysis_output/anomaly_cross_report.tex
"""

from __future__ import annotations

import csv

import anomaly_common as ac

OUT = ac.OUT_DIR / "anomaly_cross_report.tex"


def read(path):
    with path.open(encoding="utf-8") as f:
        return list(csv.DictReader(f))


def num(s: str) -> float:
    return float(s.replace(",", ""))


def money(x: float) -> str:
    return "\\$" + f"{abs(x):,.0f}".replace(",", "{,}")


def main() -> None:
    lme = {r["term"]: r for r in read(ac.OUT_DIR / "lme4_growth_model_summary.csv")}
    growth = next(r for t, r in lme.items() if t.startswith("MHI growth gap"))
    level = next(r for t, r in lme.items() if t.startswith("MHI level gap"))
    entry = {r["analysis"]: r for r in read(ac.OUT_DIR / "entry_cohort_growth_summary.csv")}
    matched_fe = num(entry["Matched FE (±1 year)"]["estimate"])
    matched_avg = num(entry["Matched average slope gap (first 5 years)"]["estimate"])
    subject = next(r for r in read(ac.PRIVATE / "anomaly_inputs.csv") if r["is_subject"] == "1")
    years = int(subject["years_since_hire"])
    res = {r["spec"]: r for r in read(ac.OUT_DIR / "anomaly_subject_results.csv")}

    lo_slope, hi_slope = sorted([abs(matched_fe), abs(matched_avg)])
    macros = {
        "XMarchGrowthGap": money(num(growth["estimate"])),
        "XMarchGrowthLo": money(num(growth["ci_upper"])), "XMarchGrowthHi": money(num(growth["ci_lower"])),
        "XMarchLevelGap": money(num(level["estimate"])),
        "XMarchAlignedLo": money(lo_slope), "XMarchAlignedHi": money(hi_slope),
        "XYearsSinceHire": years,
        "XMarchCumLme": money(abs(num(growth["estimate"])) * years),
        "XMarchCumLo": money(lo_slope * years), "XMarchCumHi": money(hi_slope * years),
        "XOneGap": money(float(res["S1_main"]["gap"])), "XTwoGap": money(float(res["S2_main"]["gap"])),
    }
    lines = ["% Generated by scripts/anomaly_cross_report.py. Do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ac.ROOT)}")
    for k, v in macros.items():
        print(f"  {k} = {v}")


if __name__ == "__main__":
    main()
